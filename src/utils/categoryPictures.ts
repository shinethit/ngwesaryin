/**
 * [v7.6.48] Resolve the icon VALUE for a sub-category, on read.
 * Own `icon` wins; else the default-id map; else the parent
 * category's resolved icon (pictorial `pic:` form when the parent
 * resolves to a pictorial, else the parent's raw icon value); else
 * 'Tag'. Callers pass the result WITHOUT a categoryId so a lucide
 * sub icon is never overridden by the parent pictorial. Rendering
 * never checks the plan and stored data is never rewritten.
 */
export function resolveSubCategoryIconValue(
  sub: SubCategory | null | undefined,
  parent: { icon?: string | null; id?: string | null } | null | undefined,
): string {
  if (sub?.icon) return sub.icon;
  if (sub?.id) {
    const mapped = DEFAULT_SUBCATEGORY_ICONS[sub.id];
    if (mapped) return mapped;
  }
  if (parent) {
    const parentPictorial = resolvePictorialIcon({
      categoryId: parent.id,
      iconName: parent.icon,
    });
    if (parentPictorial) return `pic:${parentPictorial}`;
    if (parent.icon) return parent.icon;
  }
  return 'Tag';
}


